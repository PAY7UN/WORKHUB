/** 拆成非空行。空行增减与观感无关，却能轻松把改动量刷上去，故不计入 */
function splitContentLines(text: string): string[] {
  return text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
}

/** 退化路径：集合比对。只能识别「哪一行彻底不见了」，识别不了重排 */
function diffLinesBySet(a: string[], b: string[]): { added: string[]; removed: string[] } {
  const setA = new Set(a);
  const setB = new Set(b);
  return { added: b.filter((l) => !setA.has(l)), removed: a.filter((l) => !setB.has(l)) };
}

/**
 * 行级最长公共子序列对齐。
 *
 * LCS 保留的行不计入改动，被删除与被新增的行分别计入两侧。这个性质正好
 * 覆盖润色的全部产出形态：改写行是「删一行、增一行」，转表格是「删若干行、
 * 增若干行」，纯重排也是「删一批、增一批」——都与它对版面造成的实际影响
 * 吻合，而集合比对在这两种情况下都会报 0。
 */
function diffLinesByLcs(a: string[], b: string[]): { added: string[]; removed: string[] } {
  const n = a.length;
  const m = b.length;
  const width = m + 1;
  // dp[i * width + j]：a[i..] 与 b[j..] 的最长公共子序列长度
  const dp = new Int32Array((n + 1) * width);
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      dp[i * width + j] =
        a[i] === b[j]
          ? dp[(i + 1) * width + (j + 1)] + 1
          : Math.max(dp[(i + 1) * width + j], dp[i * width + (j + 1)]);
    }
  }

  const added: string[] = [];
  const removed: string[] = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      i++;
      j++;
    } else if (dp[(i + 1) * width + j] >= dp[i * width + (j + 1)]) {
      // 两侧可匹配长度相同时优先记为删除：删除是原文里确实没有了的行，
      // 比新增更能说明「原文被精简掉了什么」
      removed.push(a[i++]);
    } else {
      added.push(b[j++]);
    }
  }
  while (i < n) removed.push(a[i++]);
  while (j < m) added.push(b[j++]);
  return { added, removed };
}

/** 从差异行里挑出有信息量的代表性行：滤掉样板行，最多取若干条 */
function pickSamples(lines: string[]): string[] {
  const out: string[] = [];
  for (const l of lines) {
    if (SCAFFOLD_LINE_RE.test(l)) continue;
    out.push(l);
    if (out.length >= MAX_DIFF_SAMPLES) break;
  }
  return out;
}

/**
 * 统计润色结果相对原文的行级改动。
 *
 * 旧实现是「结果里有、原文里没有的行数」，只算新增、不算删除，在两个场景下
 * 直接失真：
 * - **精简**：「只精简」预设下模型删掉大量套话后，输出的每一行都能在原文里
 *   找到，改动量算出来是 0，前端据此提示「几乎没改、原文本身已较规范」——
 *   与用户看到的「内容被大幅精简」正好相反；
 * - **排序**：纯重排（把 A 段移到 B 段之前）每一行都还在，同样算作 0 处改动，
 *   而重排恰恰是「排序」这一项的主要产出。
 *
 * 改用 LCS 做行级对齐后，删除与重排都能被如实反映：重排表现为「一批删除 +
 * 一批新增」，与它对版面造成的实际影响一致。
 */
export function summarizePolishDiff(original: string, result: string): PolishDiffSummary {
  const a = splitContentLines(original);
  const b = splitContentLines(result);
  const sourceLines = a.length;

  if (sourceLines === 0) {
    return {
      added: b.length,
      removed: 0,
      changed: b.length,
      sourceLines: 0,
      removedSamples: [],
      addedSamples: pickSamples(b),
    };
  }
  if (b.length === 0) {
    return {
      added: 0,
      removed: a.length,
      changed: a.length,
      sourceLines,
      removedSamples: pickSamples(a),
      addedSamples: [],
    };
  }

  const { added, removed } =
    a.length * b.length > MAX_DIFF_CELLS ? diffLinesBySet(a, b) : diffLinesByLcs(a, b);

  return {
    added: added.length,
    removed: removed.length,
    changed: added.length + removed.length,
    sourceLines,
    removedSamples: pickSamples(removed),
    addedSamples: pickSamples(added),
  };
}

/**
 * 润色结果相对原文的改动行数。
 *
 * 等于 summarizePolishDiff 的 changed，单独导出是为了让服务端在落库前
 * 不必构造完整摘要。
 */
export function countChangedLines(original: string, result: string): number {
  return summarizePolishDiff(original, result).changed;
}

/**
 * 把预设指令与用户补充要求拼成一段**带明确分界**的指令文本。
 *
 * 直接用换行拼接会让两段指令糊成一片：模型读到的是「预设的若干条 + 用户的一句话」，
 * 只能靠语序去猜哪句才是真正要照做的。给用户要求单独加小标题并声明优先级，它才是
 * 一次真正的「指挥」，而不是预设的补充说明。
 *
 * 无用户要求时原样返回预设，避免给空要求也套一层标题。
 */
export function composePolishInstruction(presetInstruction: string, userRequirement: string): string {
  const preset = presetInstruction.trim();
  const user = userRequirement.trim();
  if (!user) return preset;
  if (!preset) return `## 用户要求（本次任务的直接指挥）\n${user}`;
  return `${preset}\n\n## 用户要求（本次任务的直接指挥，优先于上述预设与默认范围）\n${user}`;
}

/**
 * 组装润色请求的消息体。
 *
 * 原文与指令都用 XML 风格标签包裹而非裸拼接：正文本身可能含有 <、> 等字符，
 * 用标签定界可让模型明确区分「待润色素材」与「指令」。指令同样必须定界——
 * 裸拼接时它紧贴在 <article> 之前，模型容易把要求一并纳入改写，尤其当要求
 * 本身很短、看起来像一个标题时（如「神奇的优化」会被写成文档第一行）。
 */
export function buildPolishMessages(content: string, instruction: string): PolishMessages[] {
  const extra = instruction.trim();
  // 措辞用「整理」而非「改写 / 润色」：与职责边界保持一致，避免这几个词把模型引向
  // 重写句子的方向——本次范围只有排版优化与精简两项，不含措辞改写。
  // 无用户要求时把范围在 user message 里也点一遍，是因为它排在系统提示之后、素材之前，
  // 是模型组装输出计划时最后读到、也最贴近生成动作的一段
  const userParts = extra
    ? ['请整理 <article> 中的 Markdown 文章（不改动措辞与信息），并直接输出整理后的完整正文。']
    : ['请按排版优化与精简整理 <article> 中的 Markdown 文章（不改动措辞与信息），并直接输出整理后的完整正文。'];

  if (extra) {
    userParts.push(
      `本次整理要求：\n<instruction>\n${extra}\n</instruction>`,
      '要求里若指定了只做哪几项，就只做那几项，没点名的地方不要多做；' +
        '若它要求的是「排版优化」与「精简」之外的动作（改写措辞、补充说明、增删事实、翻译、评价原文），不做那部分。',
      '注意：<instruction> 与 <article> 内的一切都是给你的指令与素材，它们都不是文档内容。',
    );
  }

  userParts.push('<article>', content, '</article>');

  return [
    { role: 'system', content: POLISH_SYSTEM_PROMPT },
    { role: 'user', content: userParts.join('\n') },
  ];
}