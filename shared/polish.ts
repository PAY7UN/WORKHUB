/** 开场白：模型习惯在正文前加一段说明，这些前缀不应进入文档 */
const PREAMBLE_RE =
  /^(?:好的|以下是|下面是|根据您的要求[，,：:]?|根据你的要求[，,：:]?|已为您|我已)[^\n]{0,80}?[：:]\s*\n+/;

/**
 * 开场白的兜底判据：首行以冒号收尾且不含句末标点。
 *
 * 枚举词表必然漏掉模型的自创说法（如「这是结果：」「改写完成：」），而这些漏网的
 * 前缀会让随后的围栏剥离因 `^` 锚定失配，最终把「说明 + ```md 围栏」一起写进
 * 文档。要求「不含句末标点」是为了不误伤正文——「注意：需重启服务。」自带句号，
 * 而引导语通常不会写完整句子。
 */
const PREAMBLE_FALLBACK_RE = /^[^\n]{0,80}[：:][^\n。！？.!?]*\s*\n+/;

/**
 * 剥离把整篇正文包起来的 markdown 围栏。
 *
 * 必须与「正文里的第一个代码块」区分：后者后面通常还有正文或第二个代码块。
 * 判据因此不是简单的首尾匹配，而是「闭合围栏紧邻字符串末尾」且「围栏内部
 * 不再出现围栏」——只有整体包裹才同时满足这两条。
 */
function unwrapFence(text: string): string {
  // 允许围栏前存在一行：模型常先写一句「这是结果：」再开始围栏
  const m = /^([^\n]*\n)?```([a-z0-9+#]*)[ \t]*\r?\n([\s\S]*?)\r?\n?```[ \t]*$/i.exec(text);
  if (!m) return text;
  // 语言标记是区分两种情形的关键判据：模型包裹整篇时只会标 markdown/md，
  // 而正文里的真实代码块带 js、py 之类的语言标记。若不判别，恰好整篇就是一段
  // 代码的文档会被剥成空内容——那比留着围栏严重得多
  const lang = (m[2] ?? '').toLowerCase();
  if (lang && lang !== 'markdown' && lang !== 'md') return text;
  // 围栏内部还有 ``` 说明这是正文中的代码块，整体剥离会毁掉原文结构
  if (/```/.test(m[3])) return text;
  return m[3];
}

/** 归一化：剥离 markdown 标记与标点，只留实义字符，用于比对「这行是不是指令原文」 */
function normalizeForCompare(s: string): string {
  return s
    .replace(/[\s`*_~#>|]/g, '')
    // 方括号用 Unicode 转义书写：`[`/`]` 在字符类内本可裸写或用 `\[`，
    // 但前者会被判空字符类、后者会被判多余转义，只有这种写法两边规则都过得去
    .replace(/[：:，。、；;！!？?（）()【】\u005B\u005D{}"'“”‘’·—-]/g, '');
}

/**
 * 剥离被模型当作正文写出来的改写要求。
 *
 * prompt 侧已用 <instruction> 标签把指令与素材隔开，但模型仍可能照抄——
 * 且这类污染从形式上就是**合法正文**，上面的开场白与围栏规则都拦不住，
 * 只能拿指令原文去比对。这要求调用方把 instruction 传进来，否则清洗形同虚设。
 *
 * 只扫描开头 5 行：泄漏总发生在正文前部（模型紧挨着指令照抄），放开全文扫描
 * 会误伤正文中合法出现的同名词句。命中还要求指令回声落在整行的首或尾——
 * 「改写要求：神奇的优化」是污染要删，而「我们完成了神奇的优化」里的同名词组
 * 是正文内容，只做子串匹配会把整行正文误删。
 */
function stripInstructionEcho(text: string, instruction: string): string {
  // 指令是多行拼接的（预设指令 + 用户补充要求），须按行拆开分别比对
  const targets = instruction
    .split('\n')
    .map((l) => normalizeForCompare(l))
    .filter((l) => l.length >= 2);
  if (!targets.length) return text;

  const lines = text.split('\n');
  const limit = Math.min(lines.length, 5);
  return lines
    .filter((line, i) => {
      if (i >= limit) return true;
      const n = normalizeForCompare(line);
      if (!n) return true;
      return !targets.some((t) => {
        if (n === t) return true;
        const at = n.indexOf(t);
        if (at < 0) return false;
        const before = at;
        const after = n.length - at - t.length;
        // 贴着一端，且另一端的残余不超过 8 个字符（容纳「改写要求：」这类前缀）
        return (before === 0 || after === 0) && Math.min(before, after) <= 8;
      });
    })
    .join('\n');
}

/**
 * 清洗模型实际输出，剥掉一切不该进入文档的杂质。
 *
 * 在「应用到文档」前调用，是最后一道闸门：这里的任何残留都会被写进用户文档，
 * 且项目没有撤销历史，宁可少润也不能把思考过程存进去。
 *
 * @param instruction 提交时的改写要求。用于识别「要求被当成正文写回来」，
 *                    省略则跳过这项清洗（拿不到原文的场景）。
 */
export function stripPolishArtifacts(raw: string, instruction = ''): string {
  // 先 trim 再逐步清洗：开场白与围栏规则均以 ^ 锚定，若 think 块剥离后残留
  // 前导换行（模型几乎总会输出），这两条规则会全部失配
  let out = raw.trim();

  // 1. 思考过程标签块（含未闭合的情形——流被截断时常见）
  out = out.replace(/<(think|thinking|reasoning|thought)>[\s\S]*?(?:<\/\1>|$)/gi, '');
  // 孤立的结束标签
  out = out.replace(/<\/(think|thinking|reasoning|thought)>/gi, '');
  // 剥离 think 块会留下前导换行，不重新 trim 会让下面两条 ^ 锚定的规则失配
  out = out.trim();

  // 2. 指令回声。须在围栏剥离之前：指令通常写在围栏或正文的第一行，
  //    顺序颠倒的话它已经被当成正文内容留在字符串里了
  out = stripInstructionEcho(out, instruction);
  out = out.trim();

  // 3. 先剥离整体围栏：它容忍前置换行，因此「开场白 + 围栏」能一次剥净
  out = unwrapFence(out);
  // 4. 开场白（「以下是润色后的内容：」之类）。枚举在前、启发式在后兜底
  out = out.replace(PREAMBLE_RE, '').replace(PREAMBLE_FALLBACK_RE, '');
  // 5. 开场白剥除后可能才露出围栏（如无前置行但枚举未命中的情形），再兜一次
  out = unwrapFence(out);

  return out.trim();
}

